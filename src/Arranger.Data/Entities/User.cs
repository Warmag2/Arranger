using System;
using System.ComponentModel.DataAnnotations;
using Microsoft.EntityFrameworkCore;
using Faemiyah.Repository.Entities;

namespace Faemiyah.Arranger.Data.Entities;

/// <summary>
/// An Arranger user: login credentials and personal settings.
/// </summary>
/// <remarks>
/// <see cref="EntityBaseWithUuid{TKey}.UniqueId"/> is the public user ID, used in cookies, contracts and grain calls.
/// The internal <see cref="EntityBase{TKey}.Id"/> is only used for foreign keys.
/// </remarks>
[Index(nameof(NormalizedUserName), IsUnique = true)]
public class User : EntityBaseWithUuid<long>
{
    /// <summary>
    /// The maximum length of <see cref="UserName"/>.
    /// </summary>
    public const int UserNameMaxLength = 32;

    /// <summary>
    /// The maximum length of <see cref="TimeZoneId"/>. The longest IANA identifier is about 30 characters.
    /// </summary>
    public const int TimeZoneIdMaxLength = 64;

    /// <summary>
    /// The visible handle, with the casing the user chose.
    /// </summary>
    [Required]
    [MaxLength(UserNameMaxLength)]
    public string UserName { get; set; } = string.Empty;

    /// <summary>
    /// <see cref="UserName"/> in upper case, used for case-insensitive lookups and uniqueness.
    /// </summary>
    /// <remarks>
    /// A stored column generated by PostgreSQL, so it can never disagree with <see cref="UserName"/>. Its unique
    /// index is what makes handles unique, including between concurrent registrations.
    /// </remarks>
    [MaxLength(UserNameMaxLength)]
    public string NormalizedUserName { get; set; } = string.Empty;

    /// <summary>
    /// The password hash produced by the ASP.NET Core Identity password hasher.
    /// </summary>
    [Required]
    public string PasswordHash { get; set; } = string.Empty;

    /// <summary>
    /// Changes whenever the credentials change, invalidating every cookie issued before.
    /// </summary>
    public Guid SecurityStamp { get; set; } = Guid.NewGuid();

    /// <summary>
    /// The IANA time zone times are shown in.
    /// </summary>
    [Required]
    [MaxLength(TimeZoneIdMaxLength)]
    public string TimeZoneId { get; set; } = "UTC";

    /// <summary>
    /// The ISO 4217 currency used as the base currency of arrangements this user creates.
    /// </summary>
    [Required]
    [MaxLength(3)]
    public string DefaultCurrency { get; set; } = "EUR";
}
